let ordem = 0
function produto(
  id: string,
  categoria: Categoria,
  nome: string,
  preco: number,
  descricao: string,
  medicamento?: DadosMedicamento,
  extra: Partial<Produto> = {},
): Produto {
  ordem += 1
  return {
    id: `prod-${id}`,
    categoriaId: `cat-${categoria}`,
    nome,
    descricao,
    preco,
    precoBalcao: preco,
    ativo: true,
    disponivel: true,
    destaque: false,
    oferta: false,
    ordem,
    unidade: "un",
    grupos: [],
    ...(medicamento ? { medicamento: { pmc: Math.round(preco * 118) / 100, ...medicamento } } : {}),
    ...extra,
  }
}

