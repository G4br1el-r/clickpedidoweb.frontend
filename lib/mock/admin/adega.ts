/** [nome, preço adicional, ordem] */
type ItemSeed = readonly [nome: string, precoAdicional: number, ordem: number]

type GrupoSeed = {
  nome: string
  minimo: number
  maximo: number
  gratisAte: number
  ordem: number
  itens: readonly ItemSeed[]
}

/** Monta os grupos do produto com ids estáveis: `grp-<produto>-<n>` e `opc-<produto>-<n>-<m>`. */
/**
 * Nas lojas, os combos acompanhavam os produtos pelo nome. Aqui a ligação é explícita:
 * a opção com o mesmo nome de um produto passa a apontar para ele.
 */
function ligarOpcoesAosProdutos(produtos: Produto[]): Produto[] {
  // Como as lojas comparavam: sem maiúscula, acento nem "c/".
  const chave = (nome: string) =>
    nome
      .normalize("NFD")
      .replace(/\p{Diacritic}/gu, "")
      .toLowerCase()
      .replace(/\bc\//g, "com")
      .trim()
  // Nomes que a loja escrevia diferente no combo e no cardápio.
  const apelidos: Record<string, string> = { "gelo blue ice": "gelo de blue ice (azul)" }
  const porNome = new Map(produtos.map((produto) => [chave(produto.nome), produto.id]))
  return produtos.map((produto) => ({
    ...produto,
    grupos: produto.grupos.map((grupo) => ({
      ...grupo,
      itens: grupo.itens.map((item) => {
        const nome = chave(item.nome)
        const produtoId = porNome.get(apelidos[nome] ?? nome)
        return produtoId ? { ...item, produtoId } : item
      }),
    })),
  }))
}

function grupos(produto: string, ...seeds: GrupoSeed[]): GrupoOpcao[] {
  return seeds.map((g, i) => ({
    id: `grp-${produto}-${i + 1}`,
    nome: g.nome,
    minimo: g.minimo,
    maximo: g.maximo,
    gratisAte: g.gratisAte,
    ordem: g.ordem,
    ativo: true,
    itens: g.itens.map(([nome, precoAdicional, ordem], j) => ({
      id: `opc-${produto}-${i + 1}-${j + 1}`,
      nome,
      precoAdicional,
      ordem,
      ativo: true,
    })),
  }))
}

