/**
 * Açougue Sabor da Carne: catálogo do seed da branch `feat/acougue` do sistema antigo
 * (`Data/Seed.cs`, `AtualizarCatalogoAcougueAsync`). Produtos com UnidadeMedida "KG" viram
 * `unidade: "kg"` (o preço é o do quilo); os demais, "un".
 */

/** [nome, preço adicional, ordem] */
type ItemSeed = readonly [nome: string, precoAdicional: number, ordem: number]

type GrupoSeed = {
  nome: string
  minimo: number
  maximo: number
  gratisAte: number
  ordem: number
  itens: readonly ItemSeed[]
}

/** Monta os grupos do produto com ids estáveis: `grp-<produto>-<n>` e `opc-<produto>-<n>-<m>`. */
function grupos(produto: string, ...seeds: GrupoSeed[]): GrupoOpcao[] {
  return seeds.map((g, i) => ({
    id: `grp-${produto}-${i + 1}`,
    nome: g.nome,
    minimo: g.minimo,
    maximo: g.maximo,
    gratisAte: g.gratisAte,
    ordem: g.ordem,
    ativo: true,
    itens: g.itens.map(([nome, precoAdicional, ordem], j) => ({
      id: `opc-${produto}-${i + 1}-${j + 1}`,
      nome,
      precoAdicional,
      ordem,
      ativo: true,
    })),
  }))
}

